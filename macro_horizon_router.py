# ── SAFE TYPE HELPERS ─────────────────────────────────────────────────────────

def safe_bool(val, default: bool = False) -> bool:
    """
    FIX-BOOL: Safely convert any value to bool.
    Handles: True, False, "True", "False", "true", "false",
             "1", "0", 1, 0, None.
    bool("False") == True in Python — this function fixes that.
    """
    if isinstance(val, bool):
        return val
    if val is None:
        return default
    s = str(val).strip().upper()
    if s in ("TRUE", "1", "YES", "Y"):
        return True
    if s in ("FALSE", "0", "NO", "N", "NONE", "NULL", "NAN", ""):
        return False
    return default


def safe_int(val, default: Optional[int] = None) -> Optional[int]:
    """
    FIX-DTE + QA-FIX-1: Safely convert to int without crashing on dirty values.
    Handles: "N/A", "", None, "14.5", "inf", "nan" — all return default.
    Added OverflowError catch: int(float("inf")) raises OverflowError in CPython.
    Added math.isnan/isinf guard so "inf" and "nan" strings return default cleanly.
    """
    if val is None:
        return default
    try:
        f = float(str(val).strip())
        if math.isnan(f) or math.isinf(f):
            return default
        return int(f)
    except (ValueError, TypeError, OverflowError):
        return default


def safe_float(val, default: float = 0.0) -> float:
    """PATCH 7: rejects inf as well as nan. float('inf') is valid Python and
    can enter VIX, probability, or momentum logic and distort routing silently."""
    if val is None:
        return default
    try:
        f = float(str(val).strip())
        return default if (math.isnan(f) or math.isinf(f)) else f
    except (ValueError, TypeError, OverflowError):
        return default


def safe_str(val: Any, default: str = "") -> str:
    """QA-FIX-10: Safely convert any value to stripped string."""
    if val is None:
        return default
    return str(val).strip()


def safe_list(val: Any, default: Optional[list] = None) -> list:
    """
    QA-FIX-8: Safely convert confirm_required to list.
    Handles: None, [], ["LLR_TRUE"], "LLR_TRUE" (string from JSON).
    String "LLR_TRUE" is wrapped in a list — not left as a bare string
    that works by substring accident in 'in' checks.
    """
    if default is None:
        default = []
    if val is None:
        return default
    if isinstance(val, list):
        return val
    if isinstance(val, str):
        return [val] if val.strip() else default
    return default


def _clamp(x: float, lo: float, hi: float) -> float:
    """PATCH 9/10: clamp float to [lo, hi]. Prevents macro JSON from passing
    absurd size multipliers or out-of-range confidence values."""
    return max(lo, min(hi, x))


