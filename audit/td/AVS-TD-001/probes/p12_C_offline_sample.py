def spearman(df):
    x = df.dropna(subset=["utility_v1", "utility_v2"])
    res = {}
    for d in ("CALL", "PUT", "ALL"):
        s = x if d == "ALL" else x.loc[x.direction == d]
        res[d] = {"n": len(s), "rho": None if len(s) < 3 else float(s["utility_v1"].rank().corr(s["utility_v2"].rank()))}
    return res


def within_family_spearman(df):
    rhos = []
    for _, grp in df.dropna(subset=["utility_v1", "utility_v2"]).groupby("family_id"):
        if len(grp) >= 3 and grp["utility_v1"].nunique() > 1 and grp["utility_v2"].nunique() > 1:
            rhos.append(float(grp["utility_v1"].rank().corr(grp["utility_v2"].rank())))
    s = pd.Series(rhos, dtype=float)
    top_same = 0; top_n = 0
    for _, grp in df.dropna(subset=["utility_v1", "utility_v2"]).groupby("family_id"):
        if len(grp) >= 2:
            top_n += 1; top_same += int(grp["utility_v1"].idxmax() == grp["utility_v2"].idxmax())
    return {"families": len(s), "median_rho": None if s.empty else float(s.median()),
            "iqr": None if s.empty else [float(s.quantile(.25)), float(s.quantile(.75))],
            "share_rho_below_0_7": None if s.empty else float((s < 0.7).mean()),
            "top_contract_same_v1_v2": top_same, "families_with_2plus": top_n}


