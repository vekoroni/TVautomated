def num(v):
    try:
        f = float(v)
        return f if math.isfinite(f) else None
    except (TypeError, ValueError):
        return None


def build_store(tag: str, tickers: list[str]) -> tuple[Path, OptionLiquidityLifecycleStore]:
    path = SCR / f"control_plane_scratch_{tag}.sqlite"
    for suffix in ("", "-wal", "-shm"):
        p = Path(str(path) + suffix)
        if p.exists():
            p.unlink()
    store = OptionLiquidityLifecycleStore(CanonicalRegistry(path))
    store.initialise()
    dst = sqlite3.connect(path)
    for table, where, params in (("run_registry", "run_id=?", (RUN,)),):
        rows = src.execute(f"select * from {table} where {where}", params).fetchall()
        for r in rows:
            cols = r.keys()
            dst.execute(f"insert or ignore into {table} ({','.join(cols)}) values ({','.join('?' * len(cols))})", tuple(r))
    ds_ids = set()
    for t in tickers:
        row = fam.loc[fam.ticker == t].iloc[0]
        ds_ids.update(json.loads(row["source_dataset_ids_json"]))
    dcols = [c[1] for c in dst.execute("pragma table_info(dataset_registry)")]
    for dsid in ds_ids:
        r = src.execute("select * from dataset_registry where dataset_id=?", (dsid,)).fetchone()
        if r is None:
            continue
        cols = [c for c in r.keys() if c in dcols]
        run_id = r["source_run_id"]
        if run_id and run_id != RUN:  # FK on source_run_id -> copy that run_registry row too
            rr = src.execute("select * from run_registry where run_id=?", (run_id,)).fetchone()
            if rr is not None:
                dst.execute(f"insert or ignore into run_registry ({','.join(rr.keys())}) values ({','.join('?' * len(rr.keys()))})", tuple(rr))
        dst.execute(f"insert or ignore into dataset_registry ({','.join(cols)}) values ({','.join('?' * len(cols))})", tuple(r[c] for c in cols))
    dst.commit(); dst.close()
    return path, store


